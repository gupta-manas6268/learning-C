# arithmetic operators
a = 5
b = 2

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a ** b) # power(a, b)


# Relational Operators
a = 50
b = 20

print(a == b) # False
print(a != b) # True
print(a >= b) # True




# Assignment Operators
num = 10
num *= 10
print("num:", num)



# Logical Operators
print(not False)
print(not True)
print(not (a > b))

val1 = True
val2 = False
print("AND operator:", val1 and val2)

print("OR operator", val1 or val2)