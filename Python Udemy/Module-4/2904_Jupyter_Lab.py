# Jupyter-Lab => Local Python power-shell like code 
#                 editor, with multiple window-shells.

# Open Jupyter-Lab in Browser by opening any folder
#  in Terminal by Right clicking on that folder &
#  then Run in Terminal.
# 
# Then, type 'jupyter-lab' in Command-Prompt.
#  It runs '.ipynb' files which multiple window-shells.
#  Ex: '2904_Jupyter_Lab.ipynb' file.

# Esc + b => Make another window-shell in bottom.
# 
# Esc => To escape from a window-shell.
# Firstly escape from a window-shell, then Type 
#   'a + Enter' To make another shell in top of that shell.
#  You can 'markdown' that shell, but pressing
#   'markdown' in Top-Left corner of the shell.
# Types of markdown:
#  1. Simply type & then 'Ctrl + Enter'.
#  2. Type in Comment(#) & then ...
#  3. Type in (##) & then ...

# Ctrl + Enter => Run that window-shell Python code.

# c + c + v => Copy-paste cell, & have cursor outside 
#               of cell.

# One window-shell => only gives one O/P.