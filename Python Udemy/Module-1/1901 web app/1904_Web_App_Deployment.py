# Website Deployment Options:
# 
# 1. Integrated Platforms => Easy but very limited. (Ex: streamlit, etc.)
# 2. Paas (Platform as a Service) => Focus on Development.
#                                 => Usually the best option.
#                                 => (Ex: Heroku, PythonAnywhere, Google App Engine, AWS)
#
# 3. IaaS (Infrastructure as a Service) => (Ex: DigitalOcean, AWS, Google Cloud)
#                                       =>  Digital Ocean has a better pricing system.
# 
# 4. Physical Servers => Hardest to maintain your own Servers.